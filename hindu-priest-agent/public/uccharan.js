// उच्चारण-सुधार: श्लोक और मंत्र बोलते समय आवाज़ को सही उच्चारण पर लाने के लिए।
// यहाँ बदला हुआ रूप सिर्फ़ बोलने के काम आता है। स्क्रीन पर हमेशा मूल पाठ ही दिखता है।
// ध्यान दें: ये सुधार सुनकर जाँचे नहीं गए हैं। आवाज़ें अलग-अलग होती हैं, इसलिए जो शब्द आपको गलत सुनाई दे,
// उसे नीचे WORDS में जोड़ दीजिए, जैसे 'मूल शब्द': 'बोलने का रूप'। गलत लगे तो ऐप के ऊपर "उच्चारण-सुधार" बंद भी कर सकते हैं।
(function (root) {
  // पूरे शब्द के लिए: बीज मंत्रों के अंत का अनुस्वार साफ़ "म" की तरह, और ॐ को "ओम"
  const WORDS = {
    'ॐ': 'ओम',
    'ह्रीं': 'ह्रीम', 'श्रीं': 'श्रीम', 'क्लीं': 'क्लीम', 'ऐं': 'ऐम',
    'गं': 'गम', 'हं': 'हम', 'दुं': 'दुम', 'घृणिः': 'घृणिह',
  };
  // अक्षर के स्तर के नियम (क्रम से लगते हैं)
  const RULES = [
    [/ज्ञ/g, 'ग्य'],        // ज्ञ का बोला जाने वाला रूप
    [/ः/g, 'ह'],            // विसर्ग: नमः -> नमह, शान्तिः -> शान्तिह
    [/ऽ/g, ''],             // अवग्रह चिह्न नहीं बोला जाता
    [/[०-९]+/g, ''],        // श्लोक की संख्या (जैसे १, २) नहीं बोली जाती
    [/[()]/g, ''],          // कोष्ठक नहीं बोले जाते
  ];
  const apply = (text) => {
    let t = text.split(/(\s+)/).map((tok) => {
      const m = tok.match(/^([,।॥]*)(.*?)([,।॥]*)$/);
      const core = m ? m[2] : tok;
      return WORDS[core] ? (m[1] + WORDS[core] + m[3]) : tok;
    }).join('');
    RULES.forEach(([re, to]) => { t = t.replace(re, to); });
    return t.replace(/\s+/g, ' ').trim();
  };
  const api = { WORDS, RULES, apply };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.UCCHARAN = api;
})(typeof self !== 'undefined' ? self : this);
